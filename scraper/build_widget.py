"""Build docs/widget.html from widget/ with styles.css and render.js inlined.

The published widget is then a single HTTP request (plus inventory.json and
the photos it references).

Usage:
    python -m scraper.build_widget
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

STYLESHEET_TAG = re.compile(r'<link\s+rel="stylesheet"\s+href="styles\.css"\s*/?>')
SCRIPT_TAG = re.compile(r'<script\s+src="render\.js"\s*>\s*</script>')
BANNER = "<!-- Generated by scraper/build_widget.py from widget/. Do not edit by hand. -->\n"


class BuildError(RuntimeError):
    pass


def build(source_dir: Path) -> str:
    html = (source_dir / "index.html").read_text(encoding="utf-8")
    css = (source_dir / "styles.css").read_text(encoding="utf-8")
    js = (source_dir / "render.js").read_text(encoding="utf-8")

    if "</style" in css.lower():
        raise BuildError("styles.css contains '</style', which would break inlining")
    if "</script" in js.lower():
        raise BuildError("render.js contains '</script', which would break inlining")

    html, css_count = STYLESHEET_TAG.subn(lambda _: f"<style>\n{css}</style>", html, count=1)
    html, js_count = SCRIPT_TAG.subn(lambda _: f"<script>\n{js}</script>", html, count=1)
    if css_count != 1:
        raise BuildError('index.html must contain <link rel="stylesheet" href="styles.css">')
    if js_count != 1:
        raise BuildError('index.html must contain <script src="render.js"></script>')

    doctype, _, rest = html.partition("\n")
    return f"{doctype}\n{BANNER}{rest}"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--source", type=Path, default=Path("widget"))
    parser.add_argument("--output", type=Path, default=Path("docs/widget.html"))
    args = parser.parse_args(argv)
    try:
        html = build(args.source)
    except BuildError as exc:
        print(f"build_widget: {exc}", file=sys.stderr)
        return 1
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(html, encoding="utf-8", newline="\n")
    print(f"wrote {args.output} ({len(html.encode('utf-8')):,} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
