from __future__ import annotations

import re
import shutil
from pathlib import Path

import pytest

from scraper import build_widget

WIDGET_DIR = Path(__file__).parent.parent / "widget"


@pytest.fixture
def source(tmp_path) -> Path:
    src = tmp_path / "widget"
    shutil.copytree(WIDGET_DIR, src)
    return src


def test_build_inlines_css_and_js():
    html = build_widget.build(WIDGET_DIR)
    css = (WIDGET_DIR / "styles.css").read_text(encoding="utf-8")
    js = (WIDGET_DIR / "render.js").read_text(encoding="utf-8")
    assert css in html
    assert js in html
    assert html.startswith("<!doctype html>\n<!-- Generated by")


def test_built_widget_is_a_single_request():
    html = build_widget.build(WIDGET_DIR)
    assert not re.search(r"<link[^>]+stylesheet", html)
    assert not re.search(r"<script[^>]+src=", html)
    # No third-party JS/CSS anywhere; the only absolute URL is the fallback link.
    absolute = set(re.findall(r'(?:src|href)="(https?://[^"]+)"', html))
    assert absolute == {"https://oldhickorybuildings.com/locations/eagle-idaho/"}


def test_widget_reads_inventory_by_relative_path():
    assert 'data-src="./inventory.json"' in build_widget.build(WIDGET_DIR)


def test_no_js_fallback_link_present():
    html = build_widget.build(WIDGET_DIR)
    assert "View current inventory at oldhickorybuildings.com" in html


def test_main_writes_output(tmp_path):
    out = tmp_path / "docs" / "widget.html"
    assert build_widget.main(["--source", str(WIDGET_DIR), "--output", str(out)]) == 0
    assert out.read_text(encoding="utf-8") == build_widget.build(WIDGET_DIR)


def test_missing_marker_fails(source):
    index = source / "index.html"
    html = index.read_text(encoding="utf-8").replace('src="render.js"', 'src="x.js"')
    index.write_text(html, encoding="utf-8")
    with pytest.raises(build_widget.BuildError, match=r"render\.js"):
        build_widget.build(source)


def test_closing_script_tag_in_js_fails(source):
    (source / "render.js").write_text('var s = "</script>";', encoding="utf-8")
    with pytest.raises(build_widget.BuildError, match="</script"):
        build_widget.build(source)
